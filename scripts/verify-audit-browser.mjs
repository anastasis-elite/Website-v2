// Opt-in UI verification only. The development fixture uses simulated saves.
// Real Stripe/Supabase journey verification is a separate staging requirement.
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
const origin = process.env.AUDIT_QA_ORIGIN || 'http://127.0.0.1:3100'
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(origin).hostname), 'Only isolated local QA is allowed.')
const { chromium } = await import(process.argv.find(value=>value.startsWith('--module='))?.slice(9) || process.env.PLAYWRIGHT_MODULE || 'playwright')
const output = process.env.AUDIT_QA_OUTPUT || '/tmp/anastasis-audit-browser'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const checks = []
function pass(name) { checks.push(name); console.log(`PASS ${name}`) }
try {
  for (const [name, width, height] of [['mobile',390,844],['ipad',820,1180],['desktop',1440,1000]]) {
    const context = await browser.newContext({ viewport: { width, height }, timezoneId: 'America/Chicago' })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.fulfill({ status: 204, body: '' }))
    for (const [view,tier] of [['home','ember'],['workout','ember'],['meal','ignite'],['schedule','ember']]) {
      await page.goto(`${origin}/local-dashboard-qa?view=${view}&tier=${tier}`)
      await page.getByText('Local QA fixture · simulated data and saves · no customer account', { exact:false }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${view} overflows at ${width}px`)
      await page.screenshot({ path: `${output}/${name}-${view}.png`, fullPage:true })
      pass(`${name} ${tier} ${view}: renders without horizontal overflow`)
    }
    await page.goto(`${origin}/local-dashboard-qa?view=workout&tier=ember`)
    const tracker = page.getByTestId('activity-workout-tracker')
    await tracker.getByRole('button',{name:'Save / pause',exact:true}).waitFor()
    const strength = tracker.locator('article[data-activity="strength"]').first()
    await strength.getByRole('button',{name:'Complete set 1',exact:true}).click()
    await strength.getByRole('button',{name:'Complete set 2',exact:true}).click()
    for (const kind of ['cardio','breathing','mobility']) {
      const activity = tracker.locator(`article[data-activity="${kind}"]`).first()
      assert.equal(await activity.getByText(/Weight \(/).count(),0)
      await activity.getByRole('button',{name:'Confirm activity',exact:true}).click()
    }
    await tracker.getByRole('button',{name:'Finish and review',exact:true}).click()
    await tracker.getByRole('heading',{name:'Workout complete',exact:true}).waitFor()
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('local-qa-session')))
    assert.equal(saved.completed,true)
    assert.equal(saved.exercise_logs[1].duration_unit,'minutes')
    assert.equal(saved.exercise_logs[1].actual_duration,10)
    assert.equal(saved.exercise_logs[2].actual_breaths ?? saved.exercise_logs[2].actual_reps,5)
    await page.reload()
    await page.getByText('4 of 4 exercises complete',{exact:false}).waitFor()
    pass(`${name} activity controls, completion, simulated save and reload`)
    await page.goto(`${origin}/local-dashboard-qa?view=meal&tier=ignite`)
    await page.getByLabel('Search food',{exact:true}).fill('yogurt')
    await page.getByRole('button',{name:'Search Foods',exact:true}).click()
    await page.getByRole('button',{name:/Plain Greek yogurt/}).first().click()
    await page.getByLabel('Serving amount',{exact:true}).fill('1.5')
    await page.getByLabel('Meal',{exact:true}).selectOption('Lunch')
    await page.getByRole('button',{name:'Confirm meal and save',exact:true}).click()
    await page.getByText(/Food logged. Today’s progress and remaining macros are updated./).waitFor()
    const meals = await page.evaluate(() => JSON.parse(localStorage.getItem('local-qa-meals')))
    assert.equal(meals.length,1)
    assert.equal(meals[0].entry_source,'manual')
    assert.equal(meals[0].serving_amount,1.5)
    await page.reload()
    await page.getByText('Plain Greek yogurt',{exact:true}).first().waitFor()
    pass(`${name} IGNITE manual entry independently of barcode, simulated save and reload`)
    await page.goto(`${origin}/local-dashboard-qa?view=meal&tier=ember`)
    await page.getByText('Ember includes nutrition guidance.',{exact:false}).waitFor()
    assert.equal(await page.getByRole('tab',{name:'Search / manual'}).count(),0)
    pass(`${name} EMBER guidance-only UI boundary`)
    await page.route('**/api/pricing?program=ember', route=>route.fulfill({json:{program:'ember',subscription:{available:true,amountLabel:'$360.00',intervalLabel:'per month',coverageLabel:'Recurring monthly access.'},annual:{available:false,amountLabel:'$3,600.00',intervalLabel:'one-time payment',coverageLabel:'Access period has not been confirmed.',error:'Explicit access period configuration is required.'}}}))
    await page.route('**/api/checkout',route=>route.fulfill({status:503,json:{error:'Isolated checkout provider is not configured.'}}))
    await page.goto(`${origin}/program/ember`)
    await page.getByText('$360.00 · per month',{exact:true}).waitFor()
    assert.equal(await page.getByRole('button',{name:'Pay in full',exact:true}).isDisabled(),true)
    await page.getByRole('link',{name:'Review EMBER checkout',exact:true}).click()
    await page.waitForURL('**/program/ember/cart')
    await page.getByRole('button',{name:'Choose monthly',exact:true}).click()
    await page.getByText('Isolated checkout provider is not configured.',{exact:true}).waitFor()
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    pass(`${name} checkout navigation, simulated confirmed price display, unconfirmed access period disabled, provider failure feedback`)
    await page.goto(`${origin}/audit`)
    await page.getByLabel('Name',{exact:true}).fill('Local QA')
    await page.getByLabel('Email Address',{exact:true}).fill('qa@example.test')
    await page.locator('input[name="agreement"]').check()
    await page.getByRole('button',{name:'See My Recommended Path',exact:true}).click()
    await page.getByText('Please answer every Capacity Audit question before continuing.',{exact:true}).waitFor()
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    pass(`${name} public audit validation and layout`)
    await page.goto(`${origin}/support`)
    await page.getByRole('heading',{name:'Billing help or cancellation',exact:true}).waitFor()
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    pass(`${name} customer support and billing information layout`)
    assert.deepEqual(errors,[])
    await context.close()
  }
  await writeFile(`${output}/results.json`,JSON.stringify({origin,environment:'isolated simulated browser fixture',checks},null,2))
} finally { await browser.close() }
